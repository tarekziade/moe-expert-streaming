"""Generate src/moe_expert_streaming/kernels/gguf_mm.metal from a llama.cpp (ggml) checkout.

Usage: python tools/gen_gguf_mm.py GGML_SRC_DIR   (the directory holding ggml-common.h and ggml-metal/kernels/)

Copies ggml's block structs, IQ grid tables and Metal dequantize functions (MIT, the ggml authors) for the expert types
Strata uses, and appends a grouped tile GEMM adapted from ggml's kernel_mul_mm (non-tensor path).
"""

import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
common = (src / "ggml-common.h").read_text()
dequant = (src / "ggml-metal/kernels/dequantize.h").read_text()
metal_common = (src / "ggml-metal/kernels/common.h").read_text()
out = Path(__file__).resolve().parents[1] / "src/moe_expert_streaming/kernels/gguf_mm.metal"

STRUCTS = ["block_q2_0", "block_iq2_xxs", "block_iq2_xs", "block_iq2_s", "block_iq3_xxs", "block_iq3_s", "block_iq4_nl"]
TABLES = ["kmask_iq2xs", "ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid", "iq3s_grid"]
FUNCS = ["q2_0", "iq2_xxs", "iq2_xs", "iq2_s", "iq3_xxs", "iq3_s", "iq4_nl"]


def struct(name):
    m = re.search(r"typedef struct \{[^{}]*\} " + name + ";", common)
    return m.group(0)


def table(name):
    m = re.search(r"GGML_TABLE_BEGIN\(\w+, " + name + r", \d+\).*?GGML_TABLE_END\(\)", common, re.S)
    return m.group(0)


def func(name):
    m = re.search(r"template <typename type4x4>\nvoid dequantize_" + name + r"\(.*?\n}\n", dequant, re.S)
    return m.group(0)


iq4nl = re.search(r"constexpr constant static float kvalues_iq4nl_f\[16\].*?;\n", metal_common, re.S).group(0)
parts = [
    "// Generated by tools/gen_gguf_mm.py from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors):",
    "// block structs, IQ grid tables and dequantize functions from ggml-common.h / ggml-metal/kernels/dequantize.h;",
    "// gguf_mm_tiles adapted from ggml-metal's kernel_mul_mm; gguf_mm_mpp after Strata's moe_mm.metal (MIT). Generated.",
    "#include <metal_stdlib>",
    "#include <metal_tensor>",
    "#include <MetalPerformancePrimitives/MetalPerformancePrimitives.h>",
    "using namespace metal;",
    "typedef half ggml_half;",
    "#define QK_K 256",
    "#define QK_NL 16",
    "#define QK2_0 64",
    "#define QK4_NL 32",
    "#define IQ3S_N_SCALE QK_K/64",
    "#define FOR_UNROLL(x) _Pragma(\"clang loop unroll(full)\") for (x)",
    "#define GGML_TABLE_BEGIN(type, name, size) static const constant type name[size] = {",
    "#define GGML_TABLE_END() };",
]
parts += [struct(s) for s in STRUCTS] + [table(t) for t in TABLES] + [iq4nl] + [func(f) for f in FUNCS]
parts.append((Path(__file__).parent / "gguf_mm_kernel.metal").read_text())
out.write_text("\n".join(parts) + "\n")
print(f"wrote {out} ({out.stat().st_size} bytes)")
