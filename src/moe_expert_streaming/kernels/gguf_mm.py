"""Grouped GEMM on GGUF-quantized expert banks (prefill), dequantizing inside the kernel.

``gguf_mm.metal`` is generated by ``tools/gen_gguf_mm.py`` from ggml (MIT): its block structs, IQ tables and Metal
dequantize functions, and a tile GEMM adapted from ggml's ``kernel_mul_mm``. Compiled with ``torch.mps.compile_shader``.
"""

import functools
from pathlib import Path

import torch


NAMES = {42: "q2_0", 16: "iq2_xxs", 17: "iq2_xs", 22: "iq2_s", 18: "iq3_xxs", 21: "iq3_s", 20: "iq4_nl"}
TILE_ROWS = 32


@functools.cache
def _library():
    return torch.mps.compile_shader((Path(__file__).parent / "gguf_mm.metal").read_text())


def supports(ggml_type, device):
    return torch.device(device).type == "mps" and ggml_type in NAMES


def tiles_for(counts, slots, starts=None):
    """Tiles ``(slot, first row, rows)`` int32 for rows sorted by expert: ``counts[i]`` rows from ``starts[i]`` (default:
    packed in order) use bank slot ``slots[i]``. One host synchronization (the tile count)."""
    counts = counts.to(torch.int64)
    if starts is None:
        starts = torch.cumsum(counts, 0) - counts
    per_expert = (counts + TILE_ROWS - 1) // TILE_ROWS
    total = int(per_expert.sum())
    expert = torch.repeat_interleave(torch.arange(counts.numel(), device=counts.device), per_expert, output_size=total)
    first_tile = torch.cumsum(per_expert, 0) - per_expert
    within = torch.arange(total, device=counts.device) - first_tile[expert]
    start = starts.to(torch.int64)[expert] + within * TILE_ROWS
    rows = torch.clamp(counts[expert] - within * TILE_ROWS, max=TILE_ROWS)
    return torch.stack([slots.to(counts.device)[expert], start, rows], dim=1).to(torch.int32).contiguous()


@functools.cache
def _params(n, k, row_bytes, device):
    return torch.tensor([n, k, row_bytes, n // 64], dtype=torch.int32, device=device)


def mm_tiles(bank, ggml_type, x, tiles, out=None):
    """``out[rows of tile t] = x[rows] @ bank[slot of t].T`` (float32): ``bank`` ``(slots, N, row_bytes)`` uint8,
    ``x`` ``(R, K)`` float32 sorted by expert, ``tiles`` from :func:`tiles_for`."""
    slots, n, row_bytes = bank.shape
    if n % 64 or x.shape[1] % 32:
        raise ValueError(f"gguf_mm needs N % 64 == 0 and K % 32 == 0, got {n}, {x.shape[1]}")
    if out is None:
        out = torch.empty(x.shape[0], n, dtype=torch.float32, device=x.device)
    count = tiles.shape[0] * (n // 64)
    if count:
        getattr(_library(), f"gguf_mm_tiles_{NAMES[ggml_type]}")(
            bank, x.float().contiguous(), tiles, out, _params(n, x.shape[1], row_bytes, x.device),
            threads=count * 128, group_size=128,
        )
    return out
